import type { ThemePreset } from './types'

function createDerivedPreset(
  base: ThemePreset,
  light: Record<string, string>,
  dark: Record<string, string>,
): ThemePreset {
  return {
    light: {
      ...base.light,
      ...light,
    },
    dark: {
      ...base.dark,
      ...dark,
    },
  }
}

